const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const context=vm.createContext({window:{}});
for(const name of ['battle-units','campaign-state','campaign-demo-config']){
  vm.runInContext(fs.readFileSync(path.join(__dirname,name+'.js'),'utf8'),context);
}
const {atlasCampaignDemo:config,createAtlasCampaign:create}=context.window;
const unit=(s,id)=>s.groups.find(g=>g.id===id);
const front=(s,id)=>s.fronts.find(f=>f.id===id);
const a=create(config);
let state=a.advance(12);
assert.equal(unit(state,'relief').status,'marching');
assert.equal(front(state,'west').status,'交战中');
assert(unit(state,'relief').x>25&&unit(state,'relief').x<62);
state=a.advance(49);
assert.equal(front(state,'city').status,'被围');
assert.equal(unit(state,'relief').front,'east');
a.report('east:won');
assert.equal(front(a.advance(58),'city').status,'被围');
state=a.advance(59);
assert.equal(front(state,'city').status,'解围');
assert.equal(unit(state,'garrison').morale,85);
assert.equal(state.log.filter(e=>e.id==='lift').length,1);
a.report('east:won');
assert.equal(a.snapshot().log.filter(e=>e.id==='won').length,1);
state.groups[0].x=999;
assert.notEqual(a.snapshot().groups[0].x,999);
assert.throws(()=>a.advance(58),/clock/);
const b=create(config);
b.report('east:won');
assert.equal(front(b.advance(29),'city').status,'被围');
assert.equal(front(b.advance(30),'city').status,'解围');
assert.throws(()=>create({...config,events:[{...config.events[0],after:['unknown']}]}),/dependency/);
console.log('Shared clock, journey, independent result signal, arrival, relief, morale, and reset-by-recreation passed.');

vm.runInContext(fs.readFileSync(path.join(__dirname,'campaign-changshe-config.js'),'utf8'),context);
const changsheConfig=context.window.atlasCampaignDemo;
const changshe=create(changsheConfig);
assert.equal(changshe.advance(0).log.length,0);
state=changshe.report('briefing');
assert.equal(front(state,'yanling').status,'援军集结，待命');
state=changshe.advance(8);
assert.equal(front(state,'yanling').status,'杜充按兵不动');
state=changshe.advance(80,changsheConfig.pauseAt);
assert.equal(state.log.at(-1).id,'courier');
assert.equal(state.time,15);
assert.equal(unit(state,'emperor').route,null);
const afterDeparture=seconds=>changshe.advance(15+seconds);
changshe.report('depart');
afterDeparture(18);
changshe.report('yamen');
changshe.report('conference');
changshe.report('yue');
state=afterDeparture(22);
assert.equal(unit(state,'ma').route.front,'changge');
assert.equal(unit(state,'reserve').route.front,'changge');
assert.equal(unit(state,'yue').route.front,'linying');
assert.match(changsheConfig.strengthFor(unit(state,'jin'),state.log),/推算约1.5万/);
state=afterDeparture(27);
assert.equal(unit(state,'emperor').route.front,'ford');
const departureX=unit(state,'emperor').x;
assert.equal(unit(state,'yue').route.front,'ford');
assert.equal(front(state,'changshe').status,'韩世忠受围');
state=afterDeparture(33);
assert.equal(unit(state,'river-jin').route.motion,'charge');
assert.equal(unit(state,'xu').status,'fighting');
state=afterDeparture(36);
assert.equal(unit(state,'emperor').status,'marching');
assert.ok(unit(state,'emperor').x<departureX);
assert.equal(unit(state,'xu').route.motion,'rout');
assert.equal(unit(state,'yue').status,'fighting');
assert.equal(unit(state,'wang').route.front,'ford');
state=changshe.advance(60,changsheConfig.pauseAt);
assert.equal(state.log.at(-1).id,'wang-arrival');
assert.equal(state.time,56);
assert.equal(unit(state,'xu').status,'routed');
assert.equal(unit(state,'wang').status,'fighting');
assert.equal(unit(state,'reserve').route.front,'east-road');
assert.equal(unit(state,'river-jin').x,49.5);
const approach=unit(state,'emperor');
assert.equal(approach.front,'ford');
assert.equal(approach.route,null);
state=changshe.report('emperor');
assert.equal(unit(state,'emperor').route.x,approach.x);
assert.equal(unit(state,'emperor').route.y,approach.y);
state=afterDeparture(46);
assert.equal(state.log.at(-1).id,'cross-emperor');
assert.equal(unit(state,'han').route,null);
assert.equal(unit(state,'emperor').route.x,53);
state=afterDeparture(48);
assert.equal(state.log.at(-1).id,'west-bank');
assert.equal(unit(state,'emperor').route.x,51);
assert.equal(unit(state,'han').route,null);
assert.equal(state.log.some(event=>event.id==='banner'),false);
state=afterDeparture(51);
assert.equal(state.log.at(-1).id,'breakout');
assert.ok(state.log.some(event=>event.id==='banner'));
assert.equal(unit(state,'han').route.front,'ford');
assert.equal(unit(state,'emperor').route,null);
assert.equal(unit(state,'emperor').y,17);
assert.equal(front(state,'ford').status,'赵玖已过河，郦琼奉命拆桥');
state=afterDeparture(53);
assert.equal(state.log.at(-1).id,'bridge-down');
assert.ok(unit(state,'han').route);
assert.equal(front(state,'changshe').status,'韩世忠受围');
state=afterDeparture(61);
for(const id of ['emperor','han','yue']){
  assert.equal(unit(state,id).route.motion,'standard');
  assert.equal(unit(state,id).route.front,'jin-camp');
}
state=afterDeparture(68);
assert.equal(front(state,'changshe').status,'解围');
assert.match(context.window.atlasCampaignDemo.strengthFor(unit(state,'han'),state.log),/长社已解围/);
assert.equal(changsheConfig.strengthScale(unit(state,'jin'),state.log),null);
assert.equal(unit(state,'river-jin').route.motion,'withdraw');
state=afterDeparture(70);
assert.equal(state.log.at(-1).id,'reserve-blocked');
assert.equal(unit(state,'reserve').status,'isolated');
state=afterDeparture(73);
assert.equal(unit(state,'reserve').route.front,'north-bank');
assert.equal(unit(state,'reserve').route.motion,'withdraw');
state=afterDeparture(78);
assert.equal(state.log.at(-1).id,'riverbank');
assert.equal(unit(state,'reserve').status,'withdrawing');
assert.equal(changsheConfig.strengthScale(unit(state,'reserve'),state.log),null);
state=changshe.advance(150,[changsheConfig.finishAt]);
assert.equal(state.log.at(-1).id,changsheConfig.finishAt);
assert.equal(state.time,state.log.at(-1).time);
assert.equal(front(state,'changshe').status,'解围');
assert.equal(front(state,'changge').status,'北追联络点');
assert.equal(front(state,'yanling').status,'赵玖拟经此返东京');
console.log('Changshe lure, broken formation, upstream crossing and joint advance passed.');
